// The composition root as an EXISTING FILE — the two questions `sprig build`
// has to answer before it writes <gitRoot>/serve.ts.
//
// 1. May this file be rewritten at all? Only a root the toolchain generated.
//    The test used to be a substring search for the marker over the whole file,
//    so a hand-written root that merely NAMED the marker — in the comment
//    explaining that it deliberately has none — was classified as generated:
//    `sprig build` overwrote it and `sprig clean` DELETED it. The marker is a
//    LINE of the header, not a word in the prose (REQ-011).
//
// 2. What does the rewrite have to carry across? The renderer emits from which
//    halves the BUILD can see, and it cannot see a third-party auth unit or an
//    app's own ui unit. Regenerating naively deleted `auth:` from an app that
//    composed one and every guarded route came back open; it deletes a custom
//    `ui:` the same way, and a keystone app's Frontend is what publishes the
//    config its auth path reads (REQ-012). A build must never remove what it
//    cannot see.
//
// 3. What does the refusal tell the app to do? ONE thing: build the client
//    bundle with `sprig build --ui-only <ui>` and keep serving its own root.
//    Two fixes for the same clobbered root once gave the same app opposite
//    instructions ("wrap the generated root" vs --ui-only); only --ui-only is
//    true of a root that does anything besides compose — and one line of
//    top-level code before `Bedrock()` is enough for that, since regeneration
//    carries the slots and nothing else (REQ-014).
//
// Lives in its own module so all of it is testable without running the CLI.

import {
  BEDROCK_SERVE_MARKER,
  renderServe,
} from "@techgoose-labs/bedrock/artifact";

/** The 1.x CLI's private marker. A root carrying it is by definition generated —
 *  refusing to regenerate it stranded every 1.x app at "already exists and was
 *  NOT generated" one step into the migration. */
export const LEGACY_SERVE_MARKER = "GENERATED by `sprig build --rune`";

/** One slot of `Bedrock({ ui, backend, auth })`, as read back off the file. */
export interface ServeSlot {
  from: string;
  symbol: string;
  expression: string;
}

/**
 * Is this the toolchain's own composition root — a file it may rewrite (and
 * `sprig clean` may delete)?
 *
 * True only when a line of the LEADING COMMENT BLOCK opens with a marker, which
 * is how every generator writes it:
 *
 *     // BEDROCK_SERVE_MARKER — the composition root at the git root.
 *
 * Prose that names the marker is not a marker line, so the comment documenting
 * "this file carries no marker" no longer destroys the file it protects. The
 * block ends at the first line that is neither blank nor `//`, so a pragma
 * prepended to a generated root still counts and a mention below the imports
 * does not.
 */
export function isGeneratedServe(src: string): boolean {
  return headerMarker(src) !== undefined;
}

/** Was this root written by the 1.x CLI? Decided by the same banner line, so
 *  the migration note prints for a 1.x root and not for a 2.x root whose prose
 *  happens to quote the old banner (REQ-014). */
export function isLegacyServe(src: string): boolean {
  return headerMarker(src) === LEGACY_SERVE_MARKER;
}

/** The marker that opens a line of the leading comment block — or undefined
 *  when no line does, which makes the file hand-written. */
function headerMarker(src: string): string | undefined {
  for (const line of src.split(/\r?\n/)) { // CRLF-terminated is still generated
    const comment = line.match(/^\s*\/\/\s*(.*)$/);
    if (!comment) {
      if (line.trim() === "") continue; // blank lines don't end the header
      return undefined; // code has started — the header block is over
    }
    const text = comment[1];
    for (const marker of [BEDROCK_SERVE_MARKER, LEGACY_SERVE_MARKER]) {
      if (text.startsWith(marker)) return marker;
    }
  }
  return undefined;
}

/** The argument list starting at `src[open]` (which must be `(`), balanced —
 *  `undefined` when it never closes. Quoted text is skipped so a `)` inside a
 *  string doesn't end it early. A naive `\([^)]*\)` truncates
 *  `Frontend({ app: build({ x: 1 }) })` into a file that does not parse. */
function balancedArgs(src: string, open: number): string | undefined {
  let depth = 0;
  let quote = "";
  for (let i = open; i < src.length; i++) {
    const c = src[i];
    if (quote) {
      if (c === "\\") i++;
      else if (c === quote) quote = "";
      continue;
    }
    if (c === '"' || c === "'" || c === "`") quote = c;
    else if (c === "(") depth++;
    else if (c === ")" && --depth === 0) return src.slice(open, i + 1);
  }
  return undefined;
}

/**
 * The `<slot>:` unit of an already-composed root, if it has one.
 *
 * Read back from the file rather than inferred, because nothing else in the
 * build knows about it: the unit is the app's own choice, often from a package
 * this build has never heard of. Returns undefined when there is no serve.ts,
 * no such slot, or the file is shaped in a way we cannot read confidently — in
 * which case the caller keeps the app's file (or falls back to its own default)
 * rather than guessing.
 */
export function readSlot(src: string, slot: string): ServeSlot | undefined {
  // `ui: Frontend()` / `auth: AlfredAuth()` / `auth: myUnit`
  const at = src.match(new RegExp(`\\b${slot}:\\s*([A-Za-z_$][\\w$]*)`));
  if (!at || at.index === undefined) return undefined;
  const symbol = at[1];
  const rest = src.slice(at.index + at[0].length);
  const call = rest.match(/^\s*\(/);
  let args = "";
  if (call) {
    const balanced = balancedArgs(rest, call[0].length - 1);
    if (balanced === undefined) return undefined; // half a call is worse than none
    args = balanced;
  }
  const imp = src.match(
    new RegExp(
      `import\\s*\\{[^}]*\\b${symbol}\\b[^}]*\\}\\s*from\\s*["']([^"']+)["']`,
    ),
  );
  if (!imp) return undefined;
  return { from: imp[1], symbol, expression: symbol + args };
}

async function slotOf(
  servePath: string,
  slot: string,
): Promise<ServeSlot | undefined> {
  const src = await Deno.readTextFile(servePath).catch(() => "");
  return src ? readSlot(src, slot) : undefined;
}

/** The `auth:` slot of an already-composed root — carried across every build,
 *  because losing it reopens every guarded route. */
export function existingAuthSlot(
  servePath: string,
): Promise<ServeSlot | undefined> {
  return slotOf(servePath, "auth");
}

/** The `ui:` slot of an already-composed root — carried across every build. The
 *  build's own `Frontend()` is only the DEFAULT, for a root that composes no ui
 *  unit of its own. */
export function existingUiSlot(
  servePath: string,
): Promise<ServeSlot | undefined> {
  return slotOf(servePath, "ui");
}

/** The build's default ui unit — what a root with no ui slot of its own gets. */
const DEFAULT_UI: ServeSlot = {
  from: "@techgoose-labs/sprig/bedrock",
  symbol: "Frontend",
  expression: "Frontend()",
};

export type ServeRootPlan =
  /** Leave the file alone — it is not ours to rewrite. `reason` is the message. */
  | { action: "keep"; reason: string }
  /** Write `src`. `legacy` marks a 1.x root being migrated (the CLI says so). */
  | { action: "write"; src: string; legacy: boolean };

/**
 * What to do with `<gitRoot>/serve.ts` on this build — the whole decision in one
 * place, so it is provable without running the CLI.
 */
export async function planServeRoot(
  servePath: string,
  { uiRel, serverRel, assetsRel }: {
    uiRel: string;
    serverRel: string;
    assetsRel: string;
  },
): Promise<ServeRootPlan> {
  const cur = await Deno.readTextFile(servePath).catch(() => undefined);
  if (cur !== undefined && !isGeneratedServe(cur)) {
    return {
      action: "keep",
      reason: `${servePath} already exists and was NOT generated.\n` +
        `  Refusing to overwrite a hand-written file — nothing in the tree was touched.\n` +
        `  Hand-owning the composition root on purpose — a ui unit of your own, something\n` +
        `  published before compose, any top-level code at all? Then the composed build is\n` +
        `  not yours to run: build just the client bundle, and keep serving your own root —\n` +
        `      sprig build --ui-only ${uiRel}\n` +
        `  (that is how this toolchain's own workbench builds; point your deploy build\n` +
        `  command at it too).\n` +
        `  Only the \`ui:\` slot is yours, nothing else in the file? Then you need not own\n` +
        `  it: open it with the marker line \`// ${BEDROCK_SERVE_MARKER}\` and the build\n` +
        `  regenerates it, carrying your \`ui:\` and \`auth:\` units across — and NOTHING else,\n` +
        `  so a root with top-level code stays hand-owned and builds with --ui-only above.\n` +
        `  Otherwise move the file aside (or delete it) and re-run to get the generated root.`,
    };
  }
  // CARRY THE APP'S OWN SLOTS ACROSS. The renderer emits from which halves this
  // build can see, and it can see neither a third-party auth unit nor an app's
  // own ui unit — so regenerating from scratch would silently DELETE them. The
  // build owns exactly one slot: the backend it just composed.
  const ui = await existingUiSlot(servePath) ?? DEFAULT_UI;
  const auth = await existingAuthSlot(servePath);
  const src = renderServe({
    ui,
    backend: { from: `./${serverRel}/bootstrap/mod.ts`, symbol: "api" },
    ...(auth ? { auth } : {}),
    notes: [
      `/ → the SSR app     /api/* → the keep backend     /api/docs/* → docs & cake`,
      `Re-run \`sprig build\` after changing pages/islands to refresh ${assetsRel}/.`,
      ...(auth
        ? []
        : [`Add an auth unit as the third slot when the app needs one.`]),
    ],
  });
  return {
    action: "write",
    src,
    legacy: cur !== undefined && isLegacyServe(cur),
  };
}
