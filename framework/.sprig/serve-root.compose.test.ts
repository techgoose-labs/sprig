// Integration (REQ-011, REQ-012) — the whole decision `sprig build` makes about
// <gitRoot>/serve.ts, against real files on disk: may this root be rewritten at
// all, and if so what does the rewrite carry across?
//
// The unit tests pin the two predicates; this one pins the composed outcome —
// the bytes that land on disk — because that is what destroyed a real app's
// composition root twice over (its `ui:` unit, and the file itself).

import { assert, assertEquals, assertStringIncludes } from "@std/assert";
import { join } from "@std/path";

import { planServeRoot } from "./serve-root.ts";

/** Run the plan the way the CLI does: write when it says write, leave when it doesn't. */
async function applyPlan(servePath: string) {
  const plan = await planServeRoot(servePath, {
    serverRel: "server",
    assetsRel: "ui/static",
  });
  if (plan.action === "write") await Deno.writeTextFile(servePath, plan.src);
  return plan;
}

async function withRoot(
  src: string | null,
  fn: (servePath: string) => Promise<void>,
) {
  const dir = await Deno.makeTempDir({ prefix: "serve-root-compose-" });
  const servePath = join(dir, "serve.ts");
  if (src !== null) await Deno.writeTextFile(servePath, src);
  try {
    await fn(servePath);
  } finally {
    await Deno.remove(dir, { recursive: true });
  }
}

const HAND_WRITTEN_NAMING_THE_MARKER =
  `// The composition root — HAND-WRITTEN, owned by this repo.
//
// It carries no BEDROCK_SERVE_MARKER, and that is the point: the toolchain
// refuses to overwrite a serve.ts without the marker, so this file survives
// \`sprig build\`.
import { Bedrock } from "@techgoose-labs/bedrock";
import { InfraFrontend } from "./ui/infra.ts";
import { api } from "./server/bootstrap/mod.ts";

export default Bedrock({ ui: InfraFrontend(), backend: api });
`;

Deno.test("REQ-011: a hand-written root that names the marker in prose is refused, not rewritten", async () => {
  await withRoot(HAND_WRITTEN_NAMING_THE_MARKER, async (servePath) => {
    const plan = await applyPlan(servePath);
    assertEquals(plan.action, "keep");
    assertEquals(
      await Deno.readTextFile(servePath),
      HAND_WRITTEN_NAMING_THE_MARKER,
      "the file must come out byte-identical",
    );
    if (plan.action === "keep") {
      // The refusal has to say how to opt IN, or the app's only states are
      // "silently overwritten" and "cannot build".
      assertStringIncludes(plan.reason, "BEDROCK_SERVE_MARKER");
    }
  });
});

Deno.test("REQ-011: no serve.ts at all → the root is written fresh", async () => {
  await withRoot(null, async (servePath) => {
    const plan = await applyPlan(servePath);
    assertEquals(plan.action, "write");
    const out = await Deno.readTextFile(servePath);
    assertStringIncludes(out, "// BEDROCK_SERVE_MARKER");
    assertStringIncludes(out, "ui: Frontend()");
    assertStringIncludes(out, "backend: api");
    assertStringIncludes(out, `from "./server/bootstrap/mod.ts"`);
  });
});

Deno.test("REQ-011: a generated root is regenerated, and the result is stable", async () => {
  await withRoot(null, async (servePath) => {
    await applyPlan(servePath);
    const first = await Deno.readTextFile(servePath);
    const plan = await applyPlan(servePath);
    assertEquals(plan.action, "write");
    assertEquals(plan.action === "write" && plan.legacy, false);
    assertEquals(await Deno.readTextFile(servePath), first);
  });
});

Deno.test("REQ-011: a legacy 1.x root is regenerated and flagged for the migration note", async () => {
  await withRoot(
    '// GENERATED by `sprig build --rune` — the single-origin composition root at the git root.\n' +
      `import { serveSprig } from "@sprig/keep";\n` +
      `export default serveSprig({ keep: api, app: sprigApp });\n`,
    async (servePath) => {
      const plan = await applyPlan(servePath);
      assertEquals(plan.action, "write");
      assert(plan.action === "write" && plan.legacy);
      assertStringIncludes(
        await Deno.readTextFile(servePath),
        "export default Bedrock(",
      );
    },
  );
});

Deno.test("REQ-012: regeneration carries the ui slot across, next to auth", async () => {
  await withRoot(
    `// BEDROCK_SERVE_MARKER — the composition root at the git root.
//
// Regenerated by the toolchain's init — write app code in a unit, not here.
import { Bedrock } from "@techgoose-labs/bedrock";
import { InfraFrontend } from "./ui/infra.ts";
import { AlfredAuth } from "./auth/mod.ts";
import { api } from "./server/bootstrap/mod.ts";

export default Bedrock({ ui: InfraFrontend(), backend: api, auth: AlfredAuth() });
`,
    async (servePath) => {
      const plan = await applyPlan(servePath);
      assertEquals(plan.action, "write");
      const out = await Deno.readTextFile(servePath);
      assertStringIncludes(out, "ui: InfraFrontend()");
      assertStringIncludes(out, `import { InfraFrontend } from "./ui/infra.ts"`);
      assertStringIncludes(out, "auth: AlfredAuth()");
      assertStringIncludes(out, "backend: api");
      // the build's own half is still the build's to write
      assertStringIncludes(out, `from "./server/bootstrap/mod.ts"`);
      assert(
        !out.includes("Frontend()") || out.includes("InfraFrontend()"),
        "the default Frontend() must not be re-imported over the app's unit",
      );
      assert(
        !out.includes(`"@techgoose-labs/sprig/bedrock"`),
        "nothing should pull the default ui unit in when the app composes its own",
      );
    },
  );
});

Deno.test("REQ-012: a generated root with no ui slot still gets the default Frontend()", async () => {
  await withRoot(
    `// BEDROCK_SERVE_MARKER — the composition root at the git root.
import { Bedrock } from "@techgoose-labs/bedrock";
import { api } from "./server/bootstrap/mod.ts";

export default Bedrock({ backend: api });
`,
    async (servePath) => {
      await applyPlan(servePath);
      const out = await Deno.readTextFile(servePath);
      assertStringIncludes(out, "ui: Frontend()");
      assertStringIncludes(
        out,
        `import { Frontend } from "@techgoose-labs/sprig/bedrock"`,
      );
    },
  );
});
